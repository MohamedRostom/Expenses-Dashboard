import AxeBuilder from '@axe-core/playwright';
import { expect, test } from '@playwright/test';

// The landing site (apps/landing, vite-ssg) is not part of the web app's dev server / baseURL —
// it's served by its own `landing` service in infra/docker-compose.yml (T105/T108). Override via
// E2E_LANDING_URL for other environments.
const LANDING_URL = process.env['E2E_LANDING_URL'] ?? 'http://localhost:5174';

test.describe('landing page (US9)', () => {
  test.use({ viewport: { width: 390, height: 844 } });

  test('shows the call to action, three steps and privacy link with no horizontal scroll', async ({
    page,
  }) => {
    await page.goto(LANDING_URL);

    await expect(page.getByRole('link', { name: /sign up/i })).toBeVisible();

    const steps = page.locator('.steps li');
    await expect(steps).toHaveCount(3);
    for (const step of await steps.all()) {
      await expect(step).toBeVisible();
    }

    await expect(page.getByRole('link', { name: /privacy/i })).toBeVisible();

    const hasHorizontalScroll = await page.evaluate<boolean>(() => {
      const doc = (
        globalThis as unknown as {
          document: { documentElement: { scrollWidth: number; clientWidth: number } };
        }
      ).document;
      return doc.documentElement.scrollWidth > doc.documentElement.clientWidth;
    });
    expect(hasHorizontalScroll).toBe(false);
  });

  for (const colorScheme of ['light', 'dark'] as const) {
    test(`has no accessibility violations (${colorScheme})`, async ({ page }) => {
      await page.emulateMedia({ colorScheme });
      await page.goto(LANDING_URL);
      const results = await new AxeBuilder({ page }).analyze();
      expect(results.violations).toEqual([]);
    });
  }

  test('privacy page explains the weather and places data flow', async ({ page }) => {
    await page.goto(`${LANDING_URL}/privacy`);
    const section = page.locator('#weather-privacy');
    await expect(section).toHaveText('Weather and places');
    const body = page.locator('main');
    await expect(body).toContainText('two-decimal coordinates');
    await expect(body).toContainText('No account or personal data is sent');
    await expect(body).toContainText('never stored');
    await expect(body).toContainText('always confirmed by you');
    await expect(body).toContainText('Open-Meteo.com');
    await expect(body).toContainText('CC-BY 4.0');
  });
});

// T048 (spec 004 US4). The screenshots and manifest are written by screenshots.spec.ts (T050) and
// committed from the update-snapshots artifact, so the manifest test stays red until that run.
test.describe('landing page refresh (spec 004 US4)', () => {
  test('headline, three steps and sign-up are in the first viewport at 360 x 800', async ({
    page,
  }) => {
    await page.setViewportSize({ width: 360, height: 800 });
    await page.goto(LANDING_URL);

    const targets = [
      page.getByRole('heading', { level: 1 }),
      ...(await page.locator('.steps li').all()),
      page.getByRole('link', { name: /sign up/i }),
    ];
    expect(targets).toHaveLength(5);
    for (const target of targets) {
      await expect(target).toBeVisible();
      const box = await target.boundingBox();
      expect(box).not.toBeNull();
      expect(box!.y + box!.height).toBeLessThanOrEqual(800);
    }

    const overflow = await page.evaluate<boolean>(() => {
      const doc = (
        globalThis as unknown as {
          document: { documentElement: { scrollWidth: number; clientWidth: number } };
        }
      ).document;
      return doc.documentElement.scrollWidth > doc.documentElement.clientWidth;
    });
    expect(overflow).toBe(false);
  });

  test('every screenshot is listed in the manifest as generated by screenshots.spec.ts', async ({
    page,
  }) => {
    await page.goto(LANDING_URL);
    const res = await page.request.get(`${LANDING_URL}/screenshots/manifest.json`);
    expect(res.ok()).toBe(true);
    const manifest = (await res.json()) as {
      files: { src: string; generatedBy: string }[];
    };

    const used = await page.evaluate<string[]>(() => {
      const doc = (
        globalThis as unknown as {
          document: {
            querySelectorAll(s: string): ArrayLike<{ getAttribute(n: string): string | null }>;
          };
        }
      ).document;
      return Array.from(doc.querySelectorAll('img, source'))
        .flatMap((el) => [el.getAttribute('src'), el.getAttribute('srcset')])
        .filter((v): v is string => !!v && v.startsWith('/screenshots/'));
    });
    expect(used.length).toBeGreaterThan(0);
    for (const src of used) {
      const entry = manifest.files.find((f) => f.src === src);
      expect(entry, `${src} is not in manifest.json`).toBeDefined();
      expect(entry!.generatedBy).toBe('screenshots.spec.ts');
    }
  });
});

const viewports = [
  { name: 'mobile', width: 360, height: 800 },
  { name: 'desktop', width: 1280, height: 800 },
];
for (const vp of viewports) {
  for (const colorScheme of ['light', 'dark'] as const) {
    test(`@visual landing ${colorScheme} ${vp.name}`, async ({ page }) => {
      await page.emulateMedia({ colorScheme });
      await page.setViewportSize({ width: vp.width, height: vp.height });
      await page.goto(LANDING_URL);
      await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
      await expect(page).toHaveScreenshot(`landing-${colorScheme}-${vp.name}.png`);
    });
  }
}
